#!/usr/bin/env node
/**
 * sync-program-ids.mjs — keep every hardcoded Solana program id in this repo
 * pointed at the one address the corresponding program can actually run at.
 *
 * `package.json` has declared `sync-program-ids` and `check-program-ids` since
 * long before this file existed, as `tsx scripts/sync-program-ids.ts`, and that
 * path was never in the tree (MEASURED 2026-07-31 and again 2026-08-02: no
 * `scripts/` directory at all). Both commands therefore failed on a missing
 * module before checking anything, while three other places in the repo —
 * `packages/privacy-sdk/src/constants.ts`, `packages/stark-prover/
 * deployed-verifier.json` and `packages/stark-prover/scripts/
 * deployed-verifier-check.mjs` — cited them as the thing that would catch id
 * drift. A declared command that cannot run reads as coverage and is not.
 *
 * It is `.mjs`, not `.ts`, and runs on bare `node` with no dependencies, for the
 * same reason `deployed-verifier-check.mjs` does: a gate that needs `pnpm
 * install` to have happened is a gate that silently does not run in a fresh
 * worktree. `package.json` was updated to match.
 *
 * ---------------------------------------------------------------------------
 * THE SINGLE SOURCE OF TRUTH IS `declare_id!`, NOT Anchor.toml
 * ---------------------------------------------------------------------------
 *
 * An Anchor program compares the program id it is invoked with against the
 * address baked in by `declare_id!` and rejects every instruction with
 * `DeclaredProgramIdMismatch` when they differ. So the address in
 * `programs/<crate>/src/lib.rs` is not a preference: it is the only address at
 * which a `.so` built from this tree can execute. Anchor.toml is what
 * `anchor deploy` aims at, and `constants.ts` is what clients send to; both are
 * downstream and both can be wrong.
 *
 * That is not a theoretical ordering. MEASURED 2026-08-02, read-only, against
 * https://api.devnet.solana.com — for four programs, Anchor.toml
 * `[programs.devnet]` names an address that is dead, closed, or a deployment of
 * an abandoned source lineage, while the `declare_id!` address is live:
 *
 *   p01_stark_verifier  Anchor.toml said EXmAQqm… — LIVE, slot 456289287,
 *                       797,824 B, but `solana program dump` + a byte search for
 *                       the 32-byte pubkey shows those bytes embed EXmAQqm…, so
 *                       they are not built from this tree. declare_id DGY37k3…
 *                       is LIVE, slot 469197514, 840,168 B, embeds DGY37k3….
 *                       Commit 04885979 ("P6.5 E2E smoke green — revert verifier
 *                       declare_id to DGY37k") is the source moving off EXmAQqm.
 *                       FIXED in Anchor.toml and constants.ts on 2026-08-02.
 *   zk_shielded         Anchor.toml devnet 2w4WRvuj… — `solana program dump`
 *                       answers "Program 2w4WRvuj… has been closed".
 *                       declare_id GbVM5y… is LIVE, slot 469197600.
 *   specter             Anchor.toml devnet 8rywsvhe… — "Unable to find the
 *                       account". declare_id FgKhXak… is LIVE, slot 476898022.
 *   p01_relayer         Anchor.toml devnet Ud2JYaq4… — "Unable to find the
 *                       account". declare_id 2okhzLVr… is what Anchor.toml
 *                       [programs.localnet] already carries.
 *
 * Only the first was fixed here, because the other three change which program
 * shipped clients address for zk_shielded, specter and the relayer, and that is
 * a product decision, not a STARK-verifier cleanup. THIS GATE REPORTS THEM AND
 * EXITS NON-ZERO. That is deliberate: they are true, chain-measured defects, and
 * a gate that went green while the published SDK carried a closed program id
 * would be the same class of defect this file exists to remove.
 *
 * ---------------------------------------------------------------------------
 * WHAT IS CHECKED
 * ---------------------------------------------------------------------------
 *
 *   R1  Every `programs/<crate>` with a `declare_id!` must have the same address
 *       in Anchor.toml `[programs.devnet]` and `[programs.localnet]`, when that
 *       table names the crate at all. A mismatch is a deployment that cannot
 *       execute. `[programs.mainnet]` is NOT checked: nothing in this repo has
 *       been deployed to mainnet, those entries are placeholders and legacy
 *       third-party ids, and claiming to gate them would be a claim about
 *       something never measured.
 *
 *   R2  The `<auto-generated-program-ids>` block in
 *       packages/privacy-sdk/src/constants.ts must equal what this script
 *       generates from Anchor.toml. `--write` regenerates it. Entries whose
 *       program is not in the corresponding Anchor.toml table (trustless,
 *       arcium, bundler, and everything marked "not yet deployed") are copied
 *       through VERBATIM — this generator never invents an address.
 *
 *   R3  No file in the tree may hardcode an id that belongs to a known program's
 *       id family but is not that program's canonical (`declare_id!`) address.
 *       A family is every distinct id the repo associates with one program:
 *       its `declare_id!` plus every Anchor.toml cluster entry for it. Ids
 *       outside every family are ignored — this is a drift detector, not a
 *       base58 linter. Hits in comments and in Markdown are reported separately
 *       and do not fail the run, because a comment cannot send a transaction;
 *       hits in code do fail.
 *
 * Declaration sites are exempt from R3 and checked by R1/R2 instead:
 * `Anchor.toml`, the generated block in `constants.ts`, and
 * `packages/stark-prover/deployed-verifier.json` — that last one is a
 * measurement record which deliberately names both live verifier deployments,
 * and `deployed-verifier-check.mjs` already cross-checks it against the chain.
 *
 * usage:
 *   node scripts/sync-program-ids.mjs --check    # gate, exits 1 on divergence
 *   node scripts/sync-program-ids.mjs --write    # regenerate the SDK block
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { resolve, relative, dirname, extname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => relative(REPO, p).split(sep).join('/');

// ---------------------------------------------------------------------------
// inputs
// ---------------------------------------------------------------------------

/** base58 without the four ambiguous characters, at program-id length. */
const B58_ID = /[1-9A-HJ-NP-Za-km-z]{32,44}/g;

/** Parse every `[programs.<cluster>]` table out of Anchor.toml. */
function readAnchorToml() {
  const text = readFileSync(resolve(REPO, 'Anchor.toml'), 'utf8');
  const clusters = {};
  let current = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '').trim();
    if (line.startsWith('[') && line.endsWith(']')) {
      const section = line.slice(1, -1);
      current = section.startsWith('programs.') ? section.slice('programs.'.length) : null;
      if (current !== null && clusters[current] === undefined) clusters[current] = {};
      continue;
    }
    if (current === null) continue;
    const m = line.match(/^([A-Za-z0-9_]+)\s*=\s*"([^"]+)"\s*$/);
    if (m !== null) clusters[current][m[1]] = m[2];
  }
  return clusters;
}

/**
 * Every `programs/<crate>` with a `declare_id!`, keyed by the Anchor program
 * name. Anchor keys on the crate's `[lib] name` when it has one and on
 * `[package] name` otherwise, both with `-` normalised to `_`; `programs/
 * p01-fee-splitter` is `p01_fee_splitter` for exactly that reason.
 */
function readDeclaredIds() {
  const out = {};
  const root = resolve(REPO, 'programs');
  let dirs;
  try {
    dirs = readdirSync(root, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const d of dirs) {
    if (!d.isDirectory()) continue;
    let lib;
    try {
      lib = readFileSync(resolve(root, d.name, 'src/lib.rs'), 'utf8');
    } catch {
      continue;
    }
    const m = lib.match(/declare_id!\(\s*"([^"]+)"\s*\)/);
    if (m === null) continue;

    let name = d.name;
    try {
      const cargo = readFileSync(resolve(root, d.name, 'Cargo.toml'), 'utf8');
      const libName = cargo.match(/^\s*\[lib\][\s\S]*?^\s*name\s*=\s*"([^"]+)"/m);
      const pkgName = cargo.match(/^\s*\[package\][\s\S]*?^\s*name\s*=\s*"([^"]+)"/m);
      name = (libName ?? pkgName)?.[1] ?? name;
    } catch {
      /* fall back to the directory name */
    }
    out[name.replace(/-/g, '_')] = { id: m[1], crate: `programs/${d.name}` };
  }
  return out;
}

// ---------------------------------------------------------------------------
// the SDK's generated block
// ---------------------------------------------------------------------------

const SDK_CONSTANTS = 'packages/privacy-sdk/src/constants.ts';
const OPEN = '// <auto-generated-program-ids>';
const CLOSE = '// </auto-generated-program-ids>';

/** SDK camelCase key -> Anchor.toml program key. Absent = not from Anchor.toml. */
const SDK_TO_ANCHOR = {
  zkShielded: 'zk_shielded',
  specter: 'specter',
  zkspl: 'p01_zkspl',
  relayer: 'p01_relayer',
  registry: 'p01_registry',
  feeSplitter: 'p01_fee_splitter',
  stream: 'p01_stream',
  subscription: 'p01_subscription',
  quantumVault: 'p01_quantum_vault',
  starkVerifier: 'p01_stark_verifier',
  whitelist: 'p01_whitelist',
  mugenExchange: 'p01_mugen',
};

/** SDK network name -> Anchor.toml cluster table. */
const SDK_NETWORK_TO_CLUSTER = { devnet: 'devnet', mainnet: 'mainnet' };

/**
 * Rewrite the ids inside the generated block from Anchor.toml, line by line.
 *
 * Deliberately a line rewriter and not a serialiser: every line whose program is
 * absent from the Anchor.toml table for that network is passed through
 * untouched, comment and all, so this can never invent an address for a program
 * the repo has not deployed. Returns the whole file's new text.
 */
function regenerateSdkBlock(text, clusters) {
  const lines = text.split(/\r?\n/);
  const open = lines.findIndex((l) => l.trim() === OPEN);
  const close = lines.findIndex((l) => l.trim() === CLOSE);
  if (open === -1 || close === -1 || close < open) {
    throw new Error(`${SDK_CONSTANTS}: the ${OPEN} / ${CLOSE} sentinels are missing or out of order`);
  }
  let network = null;
  for (let i = open + 1; i < close; i += 1) {
    const line = lines[i];
    const enter = line.match(/^\s*([A-Za-z0-9_]+)\s*:\s*\{\s*$/);
    if (enter !== null) {
      network = SDK_NETWORK_TO_CLUSTER[enter[1]] ?? null;
      continue;
    }
    if (/^\s*\},?\s*$/.test(line)) {
      network = null;
      continue;
    }
    const entry = line.match(/^(\s*)([A-Za-z0-9_]+)(\s*:\s*new PublicKey\(')([^']*)('\).*)$/);
    if (entry === null || network === null) continue;
    const anchorKey = SDK_TO_ANCHOR[entry[2]];
    if (anchorKey === undefined) continue;
    const want = clusters[network]?.[anchorKey];
    if (want === undefined) continue; // not in that Anchor.toml table — leave verbatim
    // The trailing text carries any `// not yet deployed` note. It stops being
    // true the moment a real id is written, so it goes with the placeholder.
    const tail = entry[4] === want ? entry[5] : "'),";
    lines[i] = `${entry[1]}${entry[2]}${entry[3]}${want}${tail}`;
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// the repo-wide sweep
// ---------------------------------------------------------------------------

const SKIP_DIRS = new Set([
  'node_modules', '.git', 'target', 'dist', 'build', '.next', '.turbo', '.anchor',
  'coverage', '.expo', '.vercel', 'out', 'vendor', '.claude', '.venv', '__pycache__',
]);

/**
 * Trees inside a SKIP_DIRS directory that are swept anyway.
 *
 * `target/` is build output everywhere except `target/idl/`, which is TRACKED,
 * is what `anchor idl`/`@coral-xyz/anchor` hand to `new Program(idl)`, and
 * carries `idl.address` — the program id an Anchor TS client uses when the
 * caller does not pass one. MEASURED 2026-08-02:
 * target/idl/p01_stark_verifier.json carries EXmAQqm..., the abandoned lineage,
 * because it was last written at commit 1023e5bb (v1.0.3). Skipping all of
 * `target/` would have made this sweep silent about the single most
 * client-facing copy of the wrong id.
 *
 * `target/types/` is tracked for the same reason and by the same `.gitignore`
 * carve-out, and it carried the SAME defect and was NOT swept. MEASURED
 * 2026-08-03: `target/types/p01_stark_verifier.ts:8` read
 * `"address": "EXmAQqm..."` while `target/idl/p01_stark_verifier.json:2` was
 * being reported by this very gate. The `.ts` twin is the `Program<T>` type
 * argument every TypeScript consumer imports, so a sweep that saw one and not
 * the other reported half the defect and called it the whole one. Both are
 * regenerated by `anchor idl build -o <json> -t <ts>`.
 */
const SCAN_ANYWAY = ['target/idl', 'target/types'];

const SCAN_EXT = new Set([
  '.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.mts', '.rs', '.toml', '.json',
  '.md', '.yml', '.yaml', '.sh', '.py', '.kt', '.swift', '.java',
]);

/**
 * Files that DECLARE ids rather than consume them. Exempt from R3 and covered by
 * R1/R2 instead. deployed-verifier.json is a measurement record that names both
 * live verifier deployments on purpose, and deployed-verifier-check.mjs already
 * refetches and re-derives every field of it that matters.
 */
const DECLARATION_SITES = new Set([
  'Anchor.toml',
  SDK_CONSTANTS,
  'packages/stark-prover/deployed-verifier.json',
  'packages/stark-prover/scripts/deployed-verifier-check.mjs',
  'scripts/sync-program-ids.mjs',
]);

/** Is this line a comment in this file type? Conservative: prose, not code. */
function isCommentLine(ext, line) {
  const t = line.trim();
  if (ext === '.md') return true;
  if (ext === '.toml' || ext === '.yml' || ext === '.yaml' || ext === '.sh' || ext === '.py') {
    return t.startsWith('#');
  }
  if (ext === '.json') return false;
  return t.startsWith('//') || t.startsWith('*') || t.startsWith('/*');
}

function* walk(dir) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const abs = resolve(dir, e.name);
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name)) continue;
      yield* walk(abs);
    } else if (e.isFile()) {
      if (!SCAN_EXT.has(extname(e.name))) continue;
      try {
        if (statSync(abs).size > 2_000_000) continue;
      } catch {
        continue;
      }
      yield abs;
    }
  }
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

const argv = process.argv.slice(2);
const WRITE = argv.includes('--write');
// --check is the default. It is still accepted explicitly because package.json
// passes it, and naming the mode at the call site is worth the redundancy.
if (WRITE && argv.includes('--check')) {
  console.error('usage: sync-program-ids.mjs [--check | --write] [--only <program>]');
  process.exit(2);
}

/**
 * `--only <program>` narrows every rule to ONE Anchor program key.
 *
 * ---------------------------------------------------------------------------
 * WHY A SCOPE FLAG EXISTS AT ALL, AND WHY IT IS NOT A WEAKENING
 * ---------------------------------------------------------------------------
 *
 * MEASURED 2026-08-03, on this tree: a bare `--check` exits 1 with 10 R1
 * divergences and 21 R3 code hits. Every single one of them belongs to a
 * program that is NOT `p01_stark_verifier` — the fee splitter, the relayer, the
 * stream, the subscription, the whitelist, zkspl, specter and zk_shielded. Each
 * one is a real, chain-measured defect (see the header), and fixing any of them
 * changes which program a shipped client addresses, which is a product decision
 * and not a cleanup.
 *
 * That combination is why this gate ran NOWHERE before today. `.github/
 * workflows/ci.yml` states in its own words, about a different step, that a
 * permanently-red required check gets deleted rather than obeyed. A repo-wide
 * blocking `--check` would have been red on its first run and gone by its
 * fourth. So the wiring is split:
 *
 *   * `--check --only p01_stark_verifier` is BLOCKING. That program measures
 *     ZERO divergences at every rule, so the gate bites the moment one appears,
 *     and it can never be red for a reason its owner cannot fix.
 *   * a bare `--check` is ADVISORY, runs on every push, and prints the full
 *     divergence count so the debt stays visible instead of being scoped away.
 *
 * The narrow mode does not relax any rule. It applies R1, R2 and R3 unchanged
 * to one program's ids. The one thing it must never do is go green because it
 * checked nothing, so it FAILS when the named program has no `declare_id!`, and
 * it prints how many ids it actually swept for.
 */
const onlyIdx = argv.indexOf('--only');
const ONLY = onlyIdx === -1 ? null : argv[onlyIdx + 1];
if (onlyIdx !== -1 && (ONLY === undefined || ONLY.startsWith('--'))) {
  console.error('usage: sync-program-ids.mjs --check --only <anchor-program-name>');
  process.exit(2);
}
if (ONLY !== null && WRITE) {
  console.error('--only narrows a CHECK; --write always regenerates the whole SDK block');
  process.exit(2);
}
/** Does this program key fall inside the current scope? */
const inScope = (key) => ONLY === null || key === ONLY;

const clusters = readAnchorToml();
const declared = readDeclaredIds();

if (ONLY !== null && declared[ONLY] === undefined) {
  console.error(`[program-ids] --only ${ONLY}: no programs/<crate>/src/lib.rs declares that program.`);
  console.error(`[program-ids] Known: ${Object.keys(declared).sort().join(', ')}`);
  console.error('[program-ids] A scope that matches nothing would pass by checking nothing.');
  process.exit(2);
}

const failures = [];
const notes = [];
const fail = (title, lines) => failures.push({ title, lines });

// --- R1: declare_id! vs Anchor.toml --------------------------------------
//
// Only devnet and localnet. See the header for why mainnet is not claimed.
const CHECKED_CLUSTERS = ['devnet', 'localnet'];
/** program key -> the address a .so from this tree can execute at. */
const CANONICAL = {};
for (const [key, { id, crate }] of Object.entries(declared).sort()) {
  CANONICAL[key] = id;
  if (!inScope(key)) continue;
  for (const cluster of CHECKED_CLUSTERS) {
    const got = clusters[cluster]?.[key];
    if (got === undefined || got === id) continue;
    fail(`Anchor.toml [programs.${cluster}] ${key} is not the address that program declares`, [
      `  declare_id!  ${id}   (${crate}/src/lib.rs)`,
      `  Anchor.toml  ${got}   ([programs.${cluster}])`,
      '',
      'Anchor rejects every instruction with DeclaredProgramIdMismatch when the address a program is',
      'invoked at is not the one it declares, so a deploy to the Anchor.toml address above produces a',
      'program that cannot execute a single instruction. One of the two is wrong; declare_id! is the',
      'one the bytecode enforces.',
    ]);
  }
}

// --- R2: the SDK's generated block ---------------------------------------
{
  const abs = resolve(REPO, SDK_CONSTANTS);
  let text = null;
  try {
    text = readFileSync(abs, 'utf8');
  } catch (e) {
    fail(`cannot read ${SDK_CONSTANTS}`, [`  ${e.message}`, 'That file is what every client resolves a program id through.']);
  }
  if (text !== null) {
    let want;
    try {
      want = regenerateSdkBlock(text, clusters);
    } catch (e) {
      fail(`cannot regenerate ${SDK_CONSTANTS}`, [`  ${e.message}`]);
    }
    if (want !== undefined && want !== text) {
      if (WRITE) {
        writeFileSync(abs, want, 'utf8');
        notes.push(`wrote ${SDK_CONSTANTS} from Anchor.toml`);
      } else {
        const a = text.split(/\r?\n/);
        const b = want.split(/\r?\n/);
        // Under `--only`, a differing line counts only when the entry it
        // rewrites belongs to the scoped program. The regeneration itself is
        // unscoped — narrowing THAT would compare the file against a partially
        // regenerated twin and could hide a divergence in the scoped program by
        // shifting line numbers.
        const scopedEntry = (line) => {
          if (ONLY === null) return true;
          const m = (line ?? '').match(/^\s*([A-Za-z0-9_]+)\s*:\s*new PublicKey\('/);
          return m !== null && SDK_TO_ANCHOR[m[1]] === ONLY;
        };
        const diff = [];
        for (let i = 0; i < Math.max(a.length, b.length); i += 1) {
          if (a[i] === b[i]) continue;
          if (!scopedEntry(a[i]) && !scopedEntry(b[i])) continue;
          diff.push(`  ${SDK_CONSTANTS}:${i + 1}`, `    on disk      ${(a[i] ?? '').trim()}`, `    Anchor.toml  ${(b[i] ?? '').trim()}`);
        }
        if (diff.length > 0) {
          fail(`${SDK_CONSTANTS} does not match Anchor.toml`, [
            ...diff,
            '',
            'That block is generated. Run `pnpm sync-program-ids` (node scripts/sync-program-ids.mjs --write).',
          ]);
        }
      }
    } else if (WRITE) {
      notes.push(`${SDK_CONSTANTS} already matches Anchor.toml`);
    }
  }
}

// --- R3: the repo-wide sweep ---------------------------------------------
//
// Build one family per program: every distinct id this repo has ever associated
// with it. Anything outside every family is somebody else's program id and is
// not this gate's business.
const FAMILY = {}; // id -> { key, canonical }
for (const [key, canonical] of Object.entries(CANONICAL)) {
  const ids = new Set([canonical]);
  for (const cluster of CHECKED_CLUSTERS) {
    const v = clusters[cluster]?.[key];
    if (v !== undefined) ids.add(v);
  }
  for (const id of ids) FAMILY[id] = { key, canonical };
}
// The verifier's abandoned deployment is not in any Anchor.toml table any more
// (it was removed on 2026-08-02) but the tree still has to be swept for it, or
// removing the last declaration would silently delete the check.
const RETIRED = {
  EXmAQqmkQmq1vnSmKXY2rnUUrrWHqxddjXaJv8aNEL4Z: 'p01_stark_verifier',
};
for (const [id, key] of Object.entries(RETIRED)) {
  if (CANONICAL[key] !== undefined && FAMILY[id] === undefined) {
    FAMILY[id] = { key, canonical: CANONICAL[key] };
  }
}

const codeHits = [];
const proseHits = [];
/** Ids swept for, after scoping. Reported so a narrow run cannot pass silently. */
const sweptIds = Object.keys(FAMILY).filter((id) => inScope(FAMILY[id].key));
const scanned = [...walk(REPO), ...SCAN_ANYWAY.flatMap((d) => [...walk(resolve(REPO, d))])];
let filesScanned = 0;
for (const abs of scanned) {
  const path = rel(abs);
  if (DECLARATION_SITES.has(path)) continue;
  const ext = extname(abs);
  let text;
  try {
    text = readFileSync(abs, 'utf8');
  } catch {
    continue;
  }
  filesScanned += 1;
  if (!/[1-9A-HJ-NP-Za-km-z]{32}/.test(text)) continue;
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    for (const m of line.matchAll(B58_ID)) {
      const fam = FAMILY[m[0]];
      if (fam === undefined || m[0] === fam.canonical) continue;
      if (!inScope(fam.key)) continue;
      const hit = { path, line: i + 1, id: m[0], ...fam, text: line.trim().slice(0, 160) };
      (isCommentLine(ext, line) ? proseHits : codeHits).push(hit);
    }
  }
}

if (codeHits.length > 0) {
  fail(`${codeHits.length} hardcoded program id${codeHits.length === 1 ? '' : 's'} in CODE diverge from declare_id!`, [
    ...codeHits.flatMap((h) => [
      `  ${h.path}:${h.line}  ${h.key}`,
      `    hardcoded   ${h.id}`,
      `    declare_id  ${h.canonical}`,
    ]),
    '',
    'Each of these compiles into something that sends a transaction to an address the program it means',
    'cannot execute at. Point them at the declare_id! address.',
  ]);
}

// ---------------------------------------------------------------------------
// report
// ---------------------------------------------------------------------------

const tag = '[program-ids]';
console.log(`${tag} mode     ${WRITE ? '--write' : '--check'}${ONLY === null ? '' : `  --only ${ONLY}`}`);
console.log(`${tag} programs ${Object.keys(CANONICAL).length} crates carry a declare_id!`);
console.log(`${tag} clusters ${CHECKED_CLUSTERS.join(', ')} (mainnet is not gated — see the header)`);
// A narrow run has to state what it actually looked at, or "PASS" below is a
// claim about nothing. `sweptIds` is the number of distinct addresses in scope
// (canonical + every superseded one this repo has associated with the program);
// zero of them would mean the sweep could not have found anything.
console.log(
  `${tag} scope    ${ONLY === null ? 'whole repo' : ONLY}: ${sweptIds.length} id${sweptIds.length === 1 ? '' : 's'} swept across ${filesScanned} files`,
);
if (sweptIds.length === 0) {
  console.error(`${tag} refusing to report on a scope with no ids to look for.`);
  process.exit(2);
}
for (const n of notes) console.log(`${tag} ${n}`);

if (proseHits.length > 0) {
  console.log('');
  console.log(`${tag} ${proseHits.length} mention${proseHits.length === 1 ? '' : 's'} of a superseded id in comments and Markdown.`);
  console.log(`${tag} Reported, not failed: prose cannot send a transaction. It can still mislead a reader.`);
  for (const h of proseHits) {
    console.log(`${tag}   ${h.path}:${h.line}  ${h.key}  ${h.id}  (declare_id ${h.canonical})`);
  }
}

if (failures.length === 0) {
  console.log('');
  console.log(
    ONLY === null
      ? `${tag} PASS — every hardcoded program id in this tree matches its declare_id!.`
      : `${tag} PASS — every hardcoded ${ONLY} id in this tree matches its declare_id!. Other programs were NOT checked; run without --only for those.`,
  );
  process.exit(0);
}

console.log('');
console.log('='.repeat(78));
console.log(`${tag} FAIL — ${failures.length} divergence${failures.length === 1 ? '' : 's'}.`);
for (const f of failures) {
  console.log('');
  console.log(`  ${f.title}`);
  for (const l of f.lines) console.log(l === '' ? '' : `  ${l}`);
}
console.log('='.repeat(78));
process.exit(1);
