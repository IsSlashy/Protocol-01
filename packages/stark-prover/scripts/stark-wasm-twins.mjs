#!/usr/bin/env node
/**
 * stark-wasm-twins.mjs — keep every inlined copy of the STARK prover WASM
 * byte-identical to `packages/stark-prover/wasm/p01_stark_bg.wasm`.
 *
 *   node scripts/stark-wasm-twins.mjs --check    # exit 1 on any drift  (CI gate)
 *   node scripts/stark-wasm-twins.mjs --write    # regenerate every twin
 *
 * # Why this exists
 *
 * `packages/stark-prover/wasm/p01_stark_bg.wasm` is a git-tracked, npm-published,
 * PREBUILT binary — the prover every client actually runs. It is inlined as
 * base64 into FOUR more tracked files so it can ship inside a JS bundle (service
 * worker, WebView, Metro bundle). Nothing in the repo regenerated any of them:
 * there is no `wasm-pack` step in any `package.json` or workflow.
 *
 * MEASURED before the Route C reship, all three generations were live at once:
 *
 *   packages/stark-prover/wasm/p01_stark_bg.wasm   192,732 B  (C0 proof 79,993 B)
 *   apps/{web,extension,mobile} twins              192,732 B  identical to it
 *   packages/react-native-zk/src/wasmData.ts       124,562 B  older still
 *
 * against a Rust prover at the same commit emitting 45,001 B for C0. Every
 * client-generated proof was old-format against the on-chain verifier.
 *
 * # What --check proves and what it does not
 *
 * --check proves the five artifacts carry the SAME bytes. It does not prove those
 * bytes match `stark/`. That is
 * `packages/stark-prover/src/wireFormat.test.ts`'s job: it drives the checked-in
 * blob and pins all seven circuits' serialized proof length against the literals
 * `programs/p01_stark_verifier/tests/route_c_trace_pair.rs:1002` pins for the Rust
 * prover. Both gates are required — this one catches a partial reship, that one
 * catches a stale reship.
 */

import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, relative } from 'node:path';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** The one true blob. Every twin below must decode to exactly these bytes. */
const CANONICAL = resolve(REPO, 'packages/stark-prover/wasm/p01_stark_bg.wasm');

/**
 * Each twin is a TS module exporting `STARK_WASM_BASE64`. `banner` is what
 * --write emits above the export; --check never looks at it.
 */
const TWINS = [
  {
    path: 'apps/web/lib/privacy/pool/starkWasmData.ts',
    banner: (n) => `/**
 * STARK WASM base64 — verbatim twin of \`apps/mobile/services/stark/wasmData.ts\`.
 *
 * AUTO-GENERATED by \`scripts/stark-wasm-twins.mjs --write\`. Do not edit by hand.
 * Regenerate after changing the prover:
 *   wasm-pack build stark --target web --out-dir wasm-out -- --features wasm
 *   cp stark/wasm-out/p01_stark_bg.wasm packages/stark-prover/wasm/
 *   cp stark/wasm-out/p01_stark.js      packages/stark-prover/wasm/
 *   node scripts/stark-wasm-twins.mjs --write
 *
 * Source: packages/stark-prover/wasm/p01_stark_bg.wasm (${n} bytes)
 *
 * The wire format is agreed with the on-chain verifier and NOTHING on the wire
 * declares which version produced a proof. A stale copy here means every proof
 * this client generates is rejected. Gated by \`--check\` in CI.
 */
`,
  },
  {
    path: 'apps/extension/src/shared/services/starkWasmData.ts',
    banner: (n) => `/**
 * STARK WASM base64 — verbatim twin of \`apps/mobile/services/stark/wasmData.ts\`.
 *
 * AUTO-GENERATED by \`scripts/stark-wasm-twins.mjs --write\`. Do not edit by hand.
 * Regenerate after changing the prover:
 *   wasm-pack build stark --target web --out-dir wasm-out -- --features wasm
 *   cp stark/wasm-out/p01_stark_bg.wasm packages/stark-prover/wasm/
 *   cp stark/wasm-out/p01_stark.js      packages/stark-prover/wasm/
 *   node scripts/stark-wasm-twins.mjs --write
 *
 * Source: packages/stark-prover/wasm/p01_stark_bg.wasm (${n} bytes)
 *
 * The wire format is agreed with the on-chain verifier and NOTHING on the wire
 * declares which version produced a proof. A stale copy here means every proof
 * this client generates is rejected. Gated by \`--check\` in CI.
 */
`,
  },
  {
    path: 'apps/mobile/services/stark/wasmData.ts',
    banner: (n) => `/**
 * STARK WASM base64 — consumed by \`services/stark/StarkProver.tsx\` (WebView).
 *
 * AUTO-GENERATED by \`scripts/stark-wasm-twins.mjs --write\`. Do not edit by hand.
 * Source: packages/stark-prover/wasm/p01_stark_bg.wasm (${n} bytes)
 *
 * The wire format is agreed with the on-chain verifier and NOTHING on the wire
 * declares which version produced a proof. A stale copy here means every proof
 * this client generates is rejected. Gated by \`--check\` in CI.
 */
`,
  },
  {
    path: 'packages/react-native-zk/src/wasmData.ts',
    banner: (n) => `/**
 * AUTO-GENERATED — DO NOT EDIT BY HAND.
 *
 * Written by \`scripts/stark-wasm-twins.mjs --write\` from the repo root, which
 * supersedes this package's own \`scripts/inline-wasm.mjs\` (that one resolved
 * \`node_modules/@protocol-01/stark-prover\` first and so pinned an even older
 * generation of the blob — MEASURED 124,562 B against a 192,732 B sibling).
 *
 * Source: packages/stark-prover/wasm/p01_stark_bg.wasm (${n} bytes)
 *
 * The wire format is agreed with the on-chain verifier and NOTHING on the wire
 * declares which version produced a proof. A stale copy here means every proof
 * this client generates is rejected. Gated by \`--check\` in CI.
 */
`,
  },
];

// ---------------------------------------------------------------------------

const mode = process.argv[2];
if (mode !== '--check' && mode !== '--write') {
  console.error('usage: node scripts/stark-wasm-twins.mjs --check | --write');
  process.exit(2);
}

let wasm;
try {
  wasm = readFileSync(CANONICAL);
} catch (e) {
  console.error(`[stark-wasm-twins] cannot read ${relative(REPO, CANONICAL)}: ${e.message}`);
  process.exit(1);
}
const base64 = wasm.toString('base64');
console.log(
  `[stark-wasm-twins] canonical ${relative(REPO, CANONICAL)} — ` +
    `${wasm.length.toLocaleString()} bytes, ${base64.length.toLocaleString()} base64 chars`,
);

/** Pull the single long base64 literal out of a twin module. */
function extractBase64(text) {
  const m = text.match(/[A-Za-z0-9+/=]{1000,}/);
  return m ? m[0] : null;
}

let failures = 0;

for (const twin of TWINS) {
  const abs = resolve(REPO, twin.path);

  if (mode === '--write') {
    writeFileSync(abs, `${twin.banner(wasm.length)}\nexport const STARK_WASM_BASE64 = '${base64}';\n`, 'utf8');
    console.log(`[stark-wasm-twins] wrote ${twin.path}`);
    continue;
  }

  let text;
  try {
    text = readFileSync(abs, 'utf8');
  } catch (e) {
    console.error(`[stark-wasm-twins] MISSING ${twin.path}: ${e.message}`);
    failures += 1;
    continue;
  }

  const got = extractBase64(text);
  if (got === null) {
    console.error(`[stark-wasm-twins] DRIFT ${twin.path}: no base64 literal found`);
    failures += 1;
    continue;
  }
  if (got === base64) {
    console.log(`[stark-wasm-twins] ok    ${twin.path}`);
    continue;
  }

  const decoded = Buffer.from(got, 'base64');
  console.error(
    `[stark-wasm-twins] DRIFT ${twin.path}: decodes to ${decoded.length.toLocaleString()} bytes, ` +
      `canonical is ${wasm.length.toLocaleString()}. This client ships a DIFFERENT prover than ` +
      `packages/stark-prover/wasm/. Fix with: node scripts/stark-wasm-twins.mjs --write`,
  );
  failures += 1;
}

// The glue is generated alongside the .wasm and its API surface must match it.
if (mode === '--check') {
  const glue = resolve(REPO, 'packages/stark-prover/wasm/p01_stark.js');
  try {
    const n = statSync(glue).size;
    if (n === 0) throw new Error('empty');
    console.log(`[stark-wasm-twins] ok    packages/stark-prover/wasm/p01_stark.js (${n.toLocaleString()} bytes)`);
  } catch (e) {
    console.error(`[stark-wasm-twins] MISSING packages/stark-prover/wasm/p01_stark.js: ${e.message}`);
    failures += 1;
  }
}

if (failures > 0) {
  console.error(`\n[stark-wasm-twins] FAIL — ${failures} artifact(s) drifted from the canonical blob.`);
  process.exit(1);
}
console.log(`\n[stark-wasm-twins] ${mode === '--write' ? 'reshipped' : 'PASS'} — ${TWINS.length} twins.`);
