#!/usr/bin/env node
/**
 * stark-glue-iife.mjs — inline the wasm-bindgen glue for the two WebView provers.
 *
 * WHY THIS EXISTS
 * ───────────────
 * `stark-wasm-twins.mjs` inlines the .wasm as base64 into four client files so
 * the prover ships inside a JS bundle. That was enough while every client
 * hand-rolled the wasm-bindgen ABI: the old blob needed exactly ONE import.
 *
 * MEASURED 2026-08-25 on the circuit-7 build: it needs TWENTY-FIVE. The spend
 * prover draws a 1,280-element CSPRNG mask (`stark/src/lib.rs` draw_spend_mask)
 * and that pulls getrandom -> crypto -> the whole wasm-bindgen shim surface.
 * The import names are CONTENT-HASHED (`__wbg_crypto_38df2bab126b63dc`), so
 * hand-writing them is work redone on every rebuild. The generated glue owns
 * them, and every client has to reach it.
 *
 * `apps/web` and `apps/extension` just import `@protocol-01/stark-prover`. The
 * two React Native surfaces cannot: their prover runs as an ES5 template string
 * inside a `<script>` in a WebView, under
 * `script-src 'unsafe-inline' 'wasm-unsafe-eval'`. There is no module system
 * there at all — no import, no require, no `type="module"`.
 *
 * So the glue is bundled to an IIFE that assigns one global, and inlined the
 * same way the blob is. MEASURED in a realm holding only WebAssembly,
 * TextDecoder, TextEncoder and crypto — what a WebView exposes and nothing
 * more: `P01StarkGlue.initSync({module})` then
 * `generate_pool_commitment_stark_proof` returns a 68,881-byte C1 proof.
 *
 * ⛔ REGENERATE THIS WHENEVER THE BLOB IS RESHIPPED. The glue is generated
 * alongside the .wasm and its import names change with it; a stale IIFE against
 * a fresh blob is a LinkError at proof time, which on this path means the
 * failure arrives after ~87 upload transactions.
 *
 *   node packages/stark-prover/scripts/stark-glue-iife.mjs --write
 *   node packages/stark-prover/scripts/stark-glue-iife.mjs --check   # CI gate
 */

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

import { REPO, GLUE } from './wasm-artifacts.mjs';

/**
 * The two surfaces that cannot import a module. Kept here rather than in
 * `wasm-artifacts.mjs` because these carry the GLUE, not the blob — a file can
 * need one and not the other, and conflating the lists is how a gate ends up
 * walking the wrong set.
 */
const GLUE_TWINS = [
  'apps/mobile/services/stark/starkGlueIife.ts',
  'packages/react-native-zk/src/glueIife.ts',
];

const GLOBAL_NAME = 'P01StarkGlue';

function buildIife() {
  const tmp = mkdtempSync(join(tmpdir(), 'p01-glue-'));
  const out = join(tmp, 'glue.iife.js');
  try {
    // `execSync` with a shell string, not execFileSync: on Windows npx is a
    // .cmd shim and execFileSync cannot spawn it directly (EINVAL).
    execSync(
      `npx esbuild "${resolve(REPO, GLUE)}" --bundle --format=iife `
      + `--global-name=${GLOBAL_NAME} --outfile="${out}"`,
      { cwd: REPO, stdio: ['ignore', 'ignore', 'inherit'] },
    );
    return readFileSync(out, 'utf8');
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

function banner(sha, bytes) {
  return `/**
 * AUTO-GENERATED by packages/stark-prover/scripts/stark-glue-iife.mjs — do not edit.
 *
 * The wasm-bindgen glue, bundled to an IIFE that assigns one global
 * (\`${GLOBAL_NAME}\`), for the two provers that run as a \`<script>\` inside a
 * WebView and have no module system to import a package from.
 *
 * Source: ${GLUE}
 * sha256: ${sha}   bytes: ${bytes}
 *
 * ⛔ REGENERATE ON EVERY BLOB RESHIP. The glue's import names are content-hashed
 * and change with the blob; a stale copy is a LinkError that lands after ~87
 * upload transactions, not at load time.
 *
 *   node packages/stark-prover/scripts/stark-glue-iife.mjs --write
 */
`;
}

const mode = process.argv.includes('--write') ? 'write'
  : process.argv.includes('--check') ? 'check' : null;
if (!mode) {
  console.error('usage: stark-glue-iife.mjs --write | --check');
  process.exit(2);
}

const iife = buildIife();
const sha = createHash('sha256').update(iife).digest('hex').slice(0, 12);
console.log(`[glue-iife] ${GLUE} -> ${iife.length.toLocaleString()} bytes IIFE, sha256 ${sha}`);

// Anti-vacuity: a bundle that lost the entry points would still be "consistent"
// across both twins and this gate would pass on a file that proves nothing.
for (const needle of [GLOBAL_NAME, 'initSync', 'generate_pool_commitment_stark_proof']) {
  if (!iife.includes(needle)) {
    console.error(`[glue-iife] FAIL — the bundle does not contain \`${needle}\`; esbuild produced something unusable.`);
    process.exit(1);
  }
}

const body = (src) => `${banner(sha, iife.length)}
export const STARK_GLUE_IIFE = ${JSON.stringify(src)};
`;

let bad = 0;
for (const rel of GLUE_TWINS) {
  const abs = resolve(REPO, rel);
  const want = body(iife);
  if (mode === 'write') {
    writeFileSync(abs, want, 'utf8');
    console.log(`[glue-iife] wrote ${rel}`);
    continue;
  }
  if (!existsSync(abs)) {
    console.error(`[glue-iife] MISSING ${rel} — run --write`);
    bad += 1;
    continue;
  }
  const got = readFileSync(abs, 'utf8');
  // Compare the payload, not the banner: the banner carries a hash that would
  // make this test its own tautology.
  const payload = (s) => (s.match(/export const STARK_GLUE_IIFE = ([\s\S]*);\n$/) || [])[1];
  if (payload(got) !== payload(want)) {
    console.error(`[glue-iife] DRIFT ${rel} — regenerate with --write`);
    bad += 1;
  } else {
    console.log(`[glue-iife] ok    ${rel}`);
  }
}

if (mode === 'check') {
  console.log(bad === 0 ? `\n[glue-iife] PASS — ${GLUE_TWINS.length} copies.`
    : `\n[glue-iife] FAIL — ${bad} copy(ies) drifted.`);
  process.exit(bad === 0 ? 0 : 1);
}
console.log(`\n[glue-iife] wrote ${GLUE_TWINS.length} copies.`);
