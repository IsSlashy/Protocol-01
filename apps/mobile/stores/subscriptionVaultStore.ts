export interface StoredVaultInfo {
  vaultAddress: string;
  retailer: string;
  tokenMint: string;
  rate: string; // bigint as string
  intervalSlots: string; // bigint as string
  isNormalMode: boolean;
  isPrivateMode: boolean;
  subscriberSecret?: string; // encrypted, only for private mode
  /** Service identifier used in the license-key HKDF info. Persisted so the
   *  license key can be re-derived later (LicenseKeyCard) from the SecureStore
   *  subscriber secret + this serviceId. */
  serviceId?: string;
  createdAt: number;
}

interface SubscriptionVaultState {
  // Persisted
  vaults: StoredVaultInfo[];

  // Transient (not persisted)
  isLoading: boolean;
  error: string | null;
  progress: string | null;

  // Actions
  addVault: (vault: StoredVaultInfo) => void;
  removeVault: (vaultAddress: string) => void;
  setLoading: (loading: boolean) => void;
  setError: (error: string | null) => void;
  setProgress: (progress: string | null) => void;
  refreshVault: (vaultAddress: string) => Promise<VaultInfo | null>;
  subscribeNormalAction: (
    config: SubscribeNormalConfig,
    vkHashSubscriber: Uint8Array,
  ) => Promise<string>;
  /** STARK variant: quantum-resistant subscribe_private using pre-verified proof buffer.
   *
   * `subscriberOwnershipCommitment` is the Goldilocks u64 Poseidon commitment of the
   * subscriber secret — same value returned by `StarkProverProvider.generateProof`
   * (circuit 0: subscriber_ownership). It is encoded as [u64_le, 24 zero bytes] and
   * stored on-chain in `vault.subscriber_commitment`; pause/resume/cancel re-derive
   * the sha256 hash from those first 8 bytes to match the circuit-0 proof. */
  subscribePrivateStarkAction: (
    receipt: ShieldReceipt,
    poolConfig: PoolConfig,
    vaultConfig: SubscribePrivateConfig,
    subscriberSecret: bigint,
    subscriberOwnershipCommitment: bigint,
    vkHashSubscriber: Uint8Array,
    starkProofData: { proofBytes: Uint8Array; publicInputs: bigint[]; proofSize: number },
    /**
     * C3 (merkle_path, circuit 3) proof — NEW on-chain hardening requirement.
     * `subscribe_private_stark` now reads a second proof buffer proving the C1
     * commitment is a leaf in the pool tree at the supplied root. publicInputs
     * layout is `[leaf_u64, root_u64, depth(=15)]`; the service derives the
     * ix `merkle_root` from `publicInputs[1]`. Generated by the caller via
     * `generateMerklePathProof`, mirroring unshield_denominated_stark_v3.
     */
    c3ProofData: { proofBytes: Uint8Array; publicInputs: bigint[]; proofSize: number },
    /**
     * Optional v1 stealth meta address (64 bytes: spending_pub || viewing_pub)
     * persisted on-chain in `vault.client_stealth_meta`. When set, cancel
     * routes the residual through `p01_relayer::submit_refund_job` instead
     * of the legacy reshield path. Build with `getOrCreateStealthMetaV1()`.
     */
    clientStealthMeta?: Uint8Array,
    /**
     * Service identifier (Service Registry slot, e.g. 'disney-plus'; falls back
     * to the stream id for custom recipients). Mixed into the license-key HKDF
     * `info` so the on-chain `license_commitment = blake3(deriveLicenseSecret(
     * subscriberSecret, serviceId))` is service-scoped. When omitted, no license
     * commitment is posted (older callers; the vault simply has none).
     */
    serviceId?: string,
  ) => Promise<{ signature: string; vaultAddress: string }>;
  /** STARK variant: quantum-resistant cancel_private_stark using pre-verified proof buffer.
   *
   * Re-shields the refundable balance back into the source pool as fresh notes owned
   * by the subscriber, pays claimable periods to the retailer, and closes the vault.
   * Dust below one denomination is forfeited (privacy tradeoff). */
  cancelPrivateStarkAction: (
    vaultAddress: string,
    subscriberSecret: bigint,
    starkProofData: { proofBytes: Uint8Array; commitment: bigint; proofSize: number },
  ) => Promise<string>;
  claimPeriodAction: (vaultAddress: string) => Promise<string>;
  pauseNormalAction: (vaultAddress: string) => Promise<string>;
  /** STARK variant: quantum-resistant pause_private using pre-verified proof buffer */
  pausePrivateStarkAction: (
    vaultAddress: string,
    starkProofData: { proofBytes: Uint8Array; commitment: bigint; proofSize: number },
  ) => Promise<string>;
  resumeNormalAction: (vaultAddress: string) => Promise<string>;
  /** STARK variant: quantum-resistant resume_private using pre-verified proof buffer */
  resumePrivateStarkAction: (
    vaultAddress: string,
    starkProofData: { proofBytes: Uint8Array; commitment: bigint; proofSize: number },
  ) => Promise<string>;
  cancelNormalAction: (vaultAddress: string, retailer: string) => Promise<string>;
  /** Force-clear a stuck subscribe/pause/resume/claim. Use when a flow was interrupted and isLoading refuses to release. */
  resetOperationState: () => void;
  /** Soft reset for wallet switches — clears the in-memory vault list but PRESERVES SecureStore secrets so archive/restore can rehydrate. */
  softReset: () => void;
  /** Scan on-chain for vaults whose subscriber commitment matches any of our spent/transferred notes (recover orphaned subscriptions).
   *
   * When `computeStarkCommitment` is supplied, STARK vaults (Goldilocks u64 commitment)
   * are also matched alongside legacy BN254 vaults — this is the cross-device recovery
   * path (seed → notes → subscriptions). Returns the newly-recovered `VaultInfo`s so the
   * caller can synthesize local Stream records. */
  recoverOrphanedVaults: (
    computeStarkCommitment?: (secretDecimal: string) => Promise<string>,
  ) => Promise<{ recovered: number; scanned: number; newVaults: VaultInfo[] }>;
  reset: () => void;
}

